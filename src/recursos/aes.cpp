Aes128::Aes128(const u8 clave[16]) {
    std::memcpy(subclaves_, clave, 16);
    u8 rcon = 1;
    for (int i = 16; i < 176; i += 4) {
        u8 t[4] = {subclaves_[i - 4], subclaves_[i - 3], subclaves_[i - 2], subclaves_[i - 1]};
        if (i % 16 == 0) {
            const u8 t0 = t[0];
            t[0] = static_cast<u8>(SBOX[t[1]] ^ rcon);
            t[1] = SBOX[t[2]];
            t[2] = SBOX[t[3]];
            t[3] = SBOX[t0];
            rcon = xtime(rcon);
        }
        for (int k = 0; k < 4; ++k) subclaves_[i + k] = static_cast<u8>(subclaves_[i - 16 + k] ^ t[k]);
    }
}

void Aes128::descifrar_bloque(u8 b[16]) const {
    auto sumar_clave = [&](int ronda) {
        for (int i = 0; i < 16; ++i) b[i] ^= subclaves_[ronda * 16 + i];
    };
    auto inv_filas_y_sbox = [&] {  // InvShiftRows + InvSubBytes (el estado va por columnas: b[c*4+fila])
        u8 t[16];
        for (int c = 0; c < 4; ++c)
            for (int f = 0; f < 4; ++f) t[((c + f) % 4) * 4 + f] = INV.v[b[c * 4 + f]];
        std::memcpy(b, t, 16);
    };
    sumar_clave(10);
    for (int ronda = 9; ronda >= 1; --ronda) {
        inv_filas_y_sbox();
        sumar_clave(ronda);
        for (int c = 0; c < 4; ++c) {  // InvMixColumns
            u8* s = b + c * 4;
            const u8 a0 = s[0], a1 = s[1], a2 = s[2], a3 = s[3];
            s[0] = static_cast<u8>(mul(a0, 14) ^ mul(a1, 11) ^ mul(a2, 13) ^ mul(a3, 9));
            s[1] = static_cast<u8>(mul(a0, 9) ^ mul(a1, 14) ^ mul(a2, 11) ^ mul(a3, 13));
            s[2] = static_cast<u8>(mul(a0, 13) ^ mul(a1, 9) ^ mul(a2, 14) ^ mul(a3, 11));
            s[3] = static_cast<u8>(mul(a0, 11) ^ mul(a1, 13) ^ mul(a2, 9) ^ mul(a3, 14));
        }
    }
    inv_filas_y_sbox();
    sumar_clave(0);
}

void descifrar_cbc(const Aes128& aes, const u8 iv[16], u8* d, size_t n) {
    const size_t completos = n / 16 * 16;
    if (completos == 0) return;
    // El resto usa el último bloque todavía cifrado: va antes que el CBC, que lo pisa.
    for (size_t i = completos; i < n; ++i) d[i] ^= d[completos - 16 + (i - completos)];
    u8 previo[16], actual[16];
    std::memcpy(previo, iv, 16);
    for (size_t p = 0; p < completos; p += 16) {
        std::memcpy(actual, d + p, 16);
        aes.descifrar_bloque(d + p);
        for (int i = 0; i < 16; ++i) d[p + i] ^= previo[i];
        std::memcpy(previo, actual, 16);
    }
}

void descifrar_aes_lineage(u8* d, size_t n) { descifrar_cbc(Aes128(CLAVE_LINEAGE), IV_LINEAGE, d, n); }

