struct SboxInversa {
    u8 v[256];
    constexpr SboxInversa() : v{} {
        for (int i = 0; i < 256; ++i) v[SBOX[i]] = static_cast<u8>(i);
    }
};
constexpr SboxInversa INV{};

constexpr u8 xtime(u8 x) { return static_cast<u8>((x << 1) ^ ((x & 0x80) ? 0x1b : 0)); }

u8 mul(u8 a, u8 b) {
    u8 r = 0;
    for (; b; b >>= 1, a = xtime(a))
        if (b & 1) r ^= a;
    return r;
}

